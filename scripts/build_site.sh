#!/usr/bin/env bash
# Build the static dashboard site into ./site (used by .github/workflows/dashboards.yml).
set -uo pipefail
OUT=${1:-site}
rm -rf "$OUT" && mkdir -p "$OUT"

# 1. Synthetic demo: always works, no network.
python -m insights demo --out "$OUT" || exit 1

# 2. A real playlist enriched from the free APIs. Failures here must not block the demo.
REAL_OK=0
if python -m insights analyze examples/heavy_and_more.csv --name "Heavy and More" --user example \
     --out "$OUT" --cache .cache/insights; then
  REAL_OK=1
fi

# 3a. Synthetic artist with planted trends (offline; shows every section of an artist page).
python -m insights artist --demo x --out "$OUT" >/dev/null 2>&1 || true

# 3b. Artist lyric studies (MusicBrainz discography + LRCLIB lyrics). One line per artist.
ARTISTS=()
if [ -f examples/artists.txt ]; then
  mapfile -t ARTISTS < <(grep -v '^\s*$' examples/artists.txt)
fi
ARTIST_LINKS=""
for a in "${ARTISTS[@]}"; do
  start=$(date +%s)
  if out=$(python -m insights artist "$a" --out "$OUT" --cache .cache/insights 2>&1 | tee /dev/stderr | grep '^Artist page: ' | tail -1); then
    path=${out#Artist page: }
    if [ -f "$path" ]; then
      rel=${path#"$OUT"/}
      ARTIST_LINKS+="<a class='c' href='${rel}'><b>${a}</b><div class='s'>Lyrics study, built in $(( $(date +%s) - start )) s</div></a>"
    fi
  fi
done

{
  echo "<!doctype html><html lang='en'><head><meta charset='utf-8'><meta name='viewport' content='width=device-width,initial-scale=1'>"
  echo "<title>Playlist Insights</title><style>"
  echo ":root{color-scheme:light;--bg:#f9f9f7;--card:#fcfcfb;--ink:#0b0b0b;--ink2:#52514e;--line:rgba(11,11,11,.1);--link:#2a78d6}"
  echo "@media (prefers-color-scheme:dark){:root{color-scheme:dark;--bg:#0d0d0d;--card:#1a1a19;--ink:#f0efec;--ink2:#c3c2b7;--line:rgba(255,255,255,.1);--link:#3987e5}}"
  echo "body{margin:0;background:var(--bg);color:var(--ink);font:16px/1.5 system-ui,-apple-system,'Segoe UI',sans-serif}"
  echo "main{max-width:760px;margin:0 auto;padding:40px 16px}a.c{display:block;background:var(--card);border:1px solid var(--line);border-radius:12px;padding:16px;margin:12px 0;color:var(--ink);text-decoration:none}"
  echo "a.c:hover{border-color:var(--link)}p{color:var(--ink2)}.s{color:var(--ink2);font-size:14px}</style></head><body><main>"
  echo "<h1>Playlist Insights</h1><p>Dashboards generated by <a href='https://github.com/Amireshhhh/playlist-ranker' style='color:var(--link)'>playlist-ranker</a>'s <code>insights</code> module.</p>"
  if [ "$REAL_OK" = 1 ]; then
    echo "<a class='c' href='example/index.html'><b>Example: Heavy and More</b><div class='s'>24 real songs, enriched live from LRCLIB, Deezer, MusicBrainz, Wikipedia (and Last.fm if a key is set).</div></a>"
  fi
  echo "<h2>Artists</h2>$ARTIST_LINKS"
  echo "<a class='c' href='artists/the-demo-whales/index.html'><b>Demo artist (synthetic)</b><div class='s'>Invented lyrics with planted trends: the tests must find exactly those.</div></a><h2>Playlists</h2>"
  echo "<a class='c' href='demo-user/index.html'><b>Demo user (synthetic data)</b><div class='s'>Three invented playlists with made-up artists and lyrics. Shows every section.</div></a>"
  echo "<p class='s'>Built $(date -u '+%Y-%m-%d %H:%M UTC') from commit ${GITHUB_SHA:-local}.</p></main></body></html>"
} > "$OUT/index.html"
touch "$OUT/.nojekyll"
echo "Site built in $OUT (real example: $REAL_OK)"
